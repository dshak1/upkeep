// Lists a target's files and sorts each into what Upkeep may do with it.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, basename } from 'node:path';

export type FileKind =
  | 'lockfile'   // regenerated by the package manager, never edited by hand
  | 'never'      // tests, tsconfig, lint, CI: Upkeep never edits these (it could make a check pass by relaxing it)
  | 'config'     // build config: only the package-name and host strings are swapped, nothing else
  | 'manifest'   // package.json
  | 'code'       // TypeScript and JavaScript source
  | 'text'       // docs and env examples: package names and hosts only
  | 'other';

const LOCKFILES = new Set(['package-lock.json', 'npm-shrinkwrap.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lock', 'bun.lockb']);
const CODE_EXT = /\.(?:[cm]?[jt]sx?)$/;
const NEVER = [
  /(^|\/)[tj]sconfig[^/]*\.json$/,
  /\.(?:test|spec)\.[cm]?[jt]sx?$/,
  /(^|\/)(?:__tests__|__mocks__|tests?|e2e|cypress|playwright)\//,
  /(^|\/)(?:vitest|jest|playwright|cypress)\.config\.[cm]?[jt]s$/,
  /(^|\/)\.eslintrc[^/]*$/,
  /(^|\/)eslint\.config\.[cm]?[jt]s$/,
  /(^|\/)\.prettierrc[^/]*$/,
  /(^|\/)biome\.jsonc?$/,
  /(^|\/)\.github\//,
  /(^|\/)\.gitlab-ci\.yml$/,
  /(^|\/)\.circleci\//,
];
const CONFIG = /(^|\/)(?:next|vite|tailwind|postcss|webpack|rollup|astro|nuxt|svelte|remix)\.config\.[cm]?[jt]s$/;
const TEXT = /(?:\.mdx?|\.txt|(^|\/)\.env(?:\.[\w-]+)*\.(?:example|sample|template))$/;

export function classify(path: string): FileKind {
  if (LOCKFILES.has(basename(path))) return 'lockfile';
  if (NEVER.some((r) => r.test(path))) return 'never';
  if (basename(path) === 'package.json') return 'manifest';
  if (CONFIG.test(path)) return 'config';
  if (CODE_EXT.test(path)) return 'code';
  if (TEXT.test(path)) return 'text';
  return 'other';
}

export function listFiles(dir: string): string[] {
  if (existsSync(join(dir, '.git'))) {
    const out = execFileSync('git', ['-C', dir, 'ls-files', '-z', '--cached', '--others', '--exclude-standard'], { maxBuffer: 1 << 28 });
    return out.toString('utf8').split('\0').filter((p) => p && !p.includes('node_modules/') && existsSync(join(dir, p)));
  }
  const files: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      if (name === 'node_modules' || name === '.git') continue;
      const p = join(d, name);
      if (statSync(p).isDirectory()) walk(p);
      else files.push(relative(dir, p));
    }
  };
  walk(dir);
  return files.sort();
}

// Text content, or null for binaries and very large files.
export function readText(path: string): string | null {
  const st = statSync(path);
  if (st.size > 2_000_000) return null;
  const buf = readFileSync(path);
  if (buf.includes(0)) return null;
  return buf.toString('utf8');
}
